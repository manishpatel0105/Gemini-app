/**
 * SAARTHI AI — Validation & Emergency Safeguards Service
 * 
 * Responsibilities:
 * 1. Strict user input validation (lengths, MIME types, image magic byte verification).
 * 2. Strict Gemini schema validation & normalization (never trust model JSON without verification).
 * 3. Evidence claim downgrading (prevent hallucinated verification).
 * 4. Deterministic Emergency Overrides (hardcoded keyword safety rules for life-threatening peril).
 */

const VALID_DOMAINS = ['MEDICAL', 'DISASTER', 'CIVIC', 'TRAFFIC', 'OTHER'];
const VALID_URGENCIES = ['Immediate', 'High', 'Moderate', 'Low', 'Unclear'];
const VALID_ACTION_PRIORITIES = ['Critical', 'High', 'Normal'];
const VALID_VERIFICATION_STATUSES = [
  'Verified',
  'Partially verified',
  'Unverified',
  'Contradicted',
  'Verification unavailable',
  'Not independently verified'
];

const ALLOWED_MIME_TYPES = ['image/png', 'image/jpeg', 'image/jpg', 'image/webp'];
const MAX_IMAGE_BYTES = 4 * 1024 * 1024; // 4 MB

/**
 * Validate incoming request for /api/analyze
 */
function validateAnalyzeRequest(body) {
  const errors = [];

  if (!body || typeof body !== 'object') {
    return { isValid: false, errors: ['Request body must be a valid JSON object.'] };
  }

  const text = typeof body.text === 'string' ? body.text.trim() : '';
  const hasImage = body.image && typeof body.image === 'object' && body.image.data;

  if (!text && !hasImage) {
    errors.push('Provide either a text description (minimum 3 characters) or an image.');
  }

  if (text && text.length < 3) {
    errors.push('Text description must be at least 3 characters long.');
  }

  if (text && text.length > 8000) {
    errors.push(`Text description exceeds maximum allowed length of 8000 characters (received ${text.length}).`);
  }

  // Optional image validation
  if (hasImage) {
    const mimeType = String(body.image.mimeType || '').toLowerCase();
    if (!ALLOWED_MIME_TYPES.includes(mimeType)) {
      errors.push(`Invalid image MIME type "${mimeType}". Allowed types: PNG, JPEG, WEBP.`);
    }

    const base64Data = String(body.image.data || '').replace(/^data:image\/\w+;base64,/, '');
    
    // Check approximate byte size from base64 string length
    const approxBytes = Math.ceil((base64Data.length * 3) / 4);
    if (approxBytes > MAX_IMAGE_BYTES) {
      errors.push(`Image size exceeds 4 MB limit (approx ${(approxBytes / (1024 * 1024)).toFixed(2)} MB).`);
    }

    // Verify magic bytes
    if (base64Data.length > 32) {
      const buffer = Buffer.from(base64Data.slice(0, 32), 'base64');
      const isSignatureValid = verifyImageMagicBytes(buffer, mimeType);
      if (!isSignatureValid) {
        errors.push('Image binary signature does not match declared MIME type.');
      }
    }
  }

  // Language validation (optional)
  if (body.language && typeof body.language !== 'string') {
    errors.push('Language must be a string code (e.g. "en-IN", "hi-IN").');
  }

  // Context validation (optional)
  const allowedContexts = ['auto', 'community_safety', 'health_notes', 'public_service', 'traffic_civic', 'emergency_crisis'];
  const rawContext = typeof body.context === 'string' ? body.context.trim().toLowerCase() : 'auto';
  const context = allowedContexts.includes(rawContext) ? rawContext : 'auto';

  return {
    isValid: errors.length === 0,
    errors,
    cleaned: {
      text,
      language: body.language || 'en-IN',
      context,
      mode: body.mode === 'demo' ? 'demo' : 'live'
    }
  };
}

/**
 * Verify magic bytes header of the uploaded image
 */
function verifyImageMagicBytes(buffer, declaredMime) {
  if (!buffer || buffer.length < 4) return false;

  // PNG signature: 89 50 4E 47 0D 0A 1A 0A
  const isPng = buffer[0] === 0x89 && buffer[1] === 0x50 && buffer[2] === 0x4E && buffer[3] === 0x47;
  // JPEG signature: FF D8 FF
  const isJpeg = buffer[0] === 0xFF && buffer[1] === 0xD8 && buffer[2] === 0xFF;
  // WEBP signature: 'RIFF' at 0, 'WEBP' at 8
  const isRiff = buffer[0] === 0x52 && buffer[1] === 0x49 && buffer[2] === 0x46 && buffer[3] === 0x46;

  if (declaredMime.includes('png')) return isPng;
  if (declaredMime.includes('jpeg') || declaredMime.includes('jpg')) return isJpeg;
  if (declaredMime.includes('webp')) return isRiff;

  return false;
}

/**
 * Normalize and strictly validate the JSON generated by Gemini
 */
function validateAndNormalizeGeminiOutput(raw, originalInput = '') {
  if (!raw || typeof raw !== 'object') {
    throw new Error('Gemini response is not a valid JSON object.');
  }

  const normalized = {};

  // 1. Title
  normalized.title = typeof raw.title === 'string' && raw.title.trim().length > 0
    ? raw.title.trim()
    : 'Emergency Response Action Plan';

  // 2. Intent
  normalized.intent = {
    said: raw.intent && typeof raw.intent.said === 'string' && raw.intent.said.trim()
      ? raw.intent.said.trim()
      : originalInput.slice(0, 300) || 'Field communication recorded',
    trueIntent: raw.intent && typeof raw.intent.trueIntent === 'string' && raw.intent.trueIntent.trim()
      ? raw.intent.trueIntent.trim()
      : 'Immediate situational triage and responder coordination'
  };

  // 3. Urgency
  // 3. Urgency (Supports Immediate/High/Moderate/Low/Unclear and low/medium/high/emergency)
  let urgency = 'Unclear';
  if (typeof raw.urgency === 'string') {
    const uLower = raw.urgency.trim().toLowerCase();
    if (uLower === 'emergency') urgency = 'Immediate';
    else if (uLower === 'medium') urgency = 'Moderate';
    else {
      const match = VALID_URGENCIES.find(u => u.toLowerCase() === uLower);
      if (match) urgency = match;
    }
  }
  normalized.urgency = urgency;

  // 4. Confidence Score (0.0 to 1.0)
  let confidence = 0.85;
  if (typeof raw.confidenceScore === 'number' && !isNaN(raw.confidenceScore)) {
    if (raw.confidenceScore > 1.0 && raw.confidenceScore <= 100.0) {
      confidence = Number((raw.confidenceScore / 100).toFixed(2));
    } else if (raw.confidenceScore >= 0.0 && raw.confidenceScore <= 1.0) {
      confidence = Number(raw.confidenceScore.toFixed(2));
    }
  }
  normalized.confidenceScore = confidence;

  // 5. Domain
  let domain = 'OTHER';
  if (typeof raw.domain === 'string') {
    const up = raw.domain.toUpperCase().trim();
    if (VALID_DOMAINS.includes(up)) domain = up;
  }
  normalized.domain = domain;

  // 6. Summary
  normalized.summary = typeof raw.summary === 'string' && raw.summary.trim()
    ? raw.summary.trim()
    : 'Situational synthesis generated from field input.';

  // 7. Facts, Unknowns, Conflicts
  normalized.facts = Array.isArray(raw.facts) ? raw.facts.map(String).filter(s => s.trim()) : [];
  normalized.unknowns = Array.isArray(raw.unknowns) ? raw.unknowns.map(String).filter(s => s.trim()) : [];
  normalized.conflicts = Array.isArray(raw.conflicts) ? raw.conflicts.map(String).filter(s => s.trim()) : [];

  // 8. Extracted Entities
  const entities = raw.extractedEntities || {};
  normalized.extractedEntities = {
    primaryIssue: typeof entities.primaryIssue === 'string' ? entities.primaryIssue.trim() : 'Unspecified incident',
    symptoms: Array.isArray(entities.symptoms) ? entities.symptoms.map(String).filter(Boolean) : [],
    history: Array.isArray(entities.history) ? entities.history.map(String).filter(Boolean) : [],
    risks: Array.isArray(entities.risks) ? entities.risks.map(String).filter(Boolean) : [],
    locationContext: typeof entities.locationContext === 'string' ? entities.locationContext.trim() : 'Location details pending'
  };

  // 9. Verification Claims (Strict Grounding Checks)
  normalized.verification = [];
  if (Array.isArray(raw.verification)) {
    for (const v of raw.verification) {
      if (!v || typeof v !== 'object') continue;
      const claim = typeof v.claim === 'string' ? v.claim.trim() : '';
      if (!claim) continue;

      let status = 'Unverified';
      if (typeof v.status === 'string') {
        const foundStatus = VALID_VERIFICATION_STATUSES.find(s => s.toLowerCase() === v.status.trim().toLowerCase());
        if (foundStatus) status = foundStatus;
      }

      // Check evidence authenticity
      const evidenceList = Array.isArray(v.evidence) ? v.evidence.map(e => ({
        source: String(e.source || 'Grounding Knowledge Base'),
        url: String(e.url || ''),
        snippet: String(e.snippet || ''),
        retrievedAt: String(e.retrievedAt || new Date().toISOString())
      })) : [];

      // GUARD: If claim claims "Verified", but evidence is empty or contains no URL/source, downgrade
      if (status === 'Verified' && evidenceList.length === 0) {
        status = 'Verification unavailable';
      }

      const primaryUrl = v.evidenceUrl || (evidenceList.length > 0 ? evidenceList[0].url : '') || '';
      const explanationText = typeof v.explanation === 'string' ? v.explanation.trim() : (typeof v.evidenceExplanation === 'string' ? v.evidenceExplanation.trim() : '');

      normalized.verification.push({
        claim,
        status,
        evidenceUrl: primaryUrl,
        evidenceExplanation: explanationText,
        evidence: evidenceList,
        explanation: explanationText
      });
    }
  }

  // 10. Actions
  normalized.actions = [];
  if (Array.isArray(raw.actions) && raw.actions.length > 0) {
    for (const act of raw.actions) {
      if (!act || typeof act !== 'object') continue;
      const step = typeof act.step === 'string' ? act.step.trim() : '';
      if (!step) continue;

      let priority = 'Normal';
      if (typeof act.priority === 'string') {
        const matched = VALID_ACTION_PRIORITIES.find(p => p.toLowerCase() === act.priority.trim().toLowerCase());
        if (matched) priority = matched;
      }

      normalized.actions.push({
        step,
        why: typeof act.why === 'string' ? act.why.trim() : 'Operational escalation',
        timing: typeof act.timing === 'string' ? act.timing.trim() : 'Prompt',
        priority,
        requiresHumanApproval: true // Non-negotiable safety guard: always requires approval
      });
    }
  } else {
    normalized.actions.push({
      step: 'Initiate Manual Dispatch Verification',
      why: 'Confirm incident details with on-scene reporting party',
      timing: 'Immediate (< 3 mins)',
      priority: 'High',
      requiresHumanApproval: true
    });
  }

  // 11. Human Guidance Steps (3 clear immediate physical steps)
  normalized.humanGuidance = Array.isArray(raw.humanGuidance) && raw.humanGuidance.length > 0
    ? raw.humanGuidance.map(String).filter(s => s.trim()).slice(0, 5)
    : [
        'Ensure personal physical safety before approaching the hazard.',
        'Contact primary emergency response services via 112 if immediate danger exists.',
        'Keep reporting channel open and observe any changes in condition or environment.'
      ];

  // 12. Draft Payloads
  normalized.draftPayloads = [];
  if (Array.isArray(raw.draftPayloads) && raw.draftPayloads.length > 0) {
    for (const dp of raw.draftPayloads) {
      if (!dp || typeof dp !== 'object') continue;
      normalized.draftPayloads.push({
        targetSystem: typeof dp.targetSystem === 'string' ? dp.targetSystem.trim() : 'INCIDENT_COORDINATION_DESK',
        actionCode: typeof dp.actionCode === 'string' ? dp.actionCode.trim() : 'INCIDENT_ESCALATION',
        priority: dp.priority === 'P1' ? 'P1' : 'P2',
        payloadSummary: typeof dp.payloadSummary === 'string' ? dp.payloadSummary.trim() : 'Draft emergency telemetry',
        sent: false // Non-negotiable: MUST be false
      });
    }
  } else {
    normalized.draftPayloads.push({
      targetSystem: 'EMERGENCY_OPS_CENTER',
      actionCode: 'CIVIC_INCIDENT_REPORT',
      priority: 'P2',
      payloadSummary: 'Triage payload drafted for supervisory operator sign-off.',
      sent: false
    });
  }

  // 13. Raw System Payload
  const rawPayload = (raw.rawSystemPayload && typeof raw.rawSystemPayload === 'object')
    ? raw.rawSystemPayload
    : {};

  normalized.rawSystemPayload = {
    header: {
      specVersion: 'SAARTHI-EOC-v1.0',
      timestampUtc: new Date().toISOString(),
      classification: 'DRAFT_SIMULATION_ONLY',
      regulatoryNotice: 'DRAFT PAYLOAD — NOT SENT TO ANY REAL SYSTEM',
      ...(rawPayload.header || {})
    },
    incident: {
      domain: normalized.domain,
      urgency: normalized.urgency,
      entities: normalized.extractedEntities,
      ...(rawPayload.incident || {})
    },
    actionDirectives: normalized.draftPayloads
  };

  // 14. Safety Note & Follow-up (Supporting both safetyNotes array and safety_note string)
  let safetyNoteStr = typeof raw.safety_note === 'string' && raw.safety_note.trim()
    ? raw.safety_note.trim()
    : 'SAFETY ADVISORY: SAARTHI AI is an information-assistance decision support tool, not an emergency service or licensed professional. Dial 112 in India for direct life-safety emergency dispatch.';
  
  let safetyNotesList = Array.isArray(raw.safetyNotes) && raw.safetyNotes.length > 0
    ? raw.safetyNotes.map(String).filter(s => s.trim())
    : [safetyNoteStr];

  normalized.safety_note = safetyNoteStr;
  normalized.safetyNotes = safetyNotesList;

  // Follow-up questions (Supporting both followUpQuestions array and follow_up_question string)
  let followUpStr = typeof raw.follow_up_question === 'string' && raw.follow_up_question.trim()
    ? raw.follow_up_question.trim()
    : 'Are there any other critical details or immediate safety hazards at this location?';

  let followUpList = Array.isArray(raw.followUpQuestions) && raw.followUpQuestions.length > 0
    ? raw.followUpQuestions.map(String).filter(s => s.trim())
    : [followUpStr];

  normalized.follow_up_question = followUpStr;
  normalized.followUpQuestions = followUpList;

  // Apply Deterministic Emergency Overrides
  return applyDeterministicEmergencyOverride(normalized, originalInput);
}

/**
 * Deterministic Emergency Overrides
 * Scans text and extracted entities for extreme life peril indicators.
 * Forces urgency to High or Immediate, prepends 112 India advice, and enforces safety constraints.
 */
function applyDeterministicEmergencyOverride(analysis, inputText = '') {
  const combinedText = `${inputText} ${analysis.extractedEntities.primaryIssue} ${analysis.extractedEntities.symptoms.join(' ')} ${analysis.extractedEntities.risks.join(' ')}`.toLowerCase();

  const emergencyMarkers = [
    {
      category: 'CARDIAC_OR_CHEST_PAIN',
      regex: /(chest\s*pain|heart\s*attack|cardiac\s*arrest|seene\s*me\s*dard|left\s*arm\s*pain|diaphoresis|stemi|angina)/i,
      minUrgency: 'Immediate',
      advice: 'POSSIBLE CARDIAC CRISIS DETECTED: Immediately dial 112 (National Emergency) or 108 (Ambulance). Keep patient seated, calm, and resting. Do not allow patient to walk or exert effort.'
    },
    {
      category: 'SEVERE_RESPIRATORY_DISTRESS',
      regex: /(difficulty\s*breathing|shortness\s*of\s*breath|saans\s*nahi\s*aa\s*rahi|choking|gasping|stridor|asphyxiat)/i,
      minUrgency: 'Immediate',
      advice: 'ACUTE BREATHING COMPROMISE DETECTED: Dial 112 / 108 immediately. Keep airway clear and ensure patient sits upright with fresh ventilation.'
    },
    {
      category: 'UNCONSCIOUSNESS',
      regex: /(unconscious|unresponsive|behoshi|behosh|fainted|coma|not\s*waking\s*up)/i,
      minUrgency: 'Immediate',
      advice: 'UNCONSCIOUS PERSON DETECTED: Dial 112 immediately. Check breathing. If breathing, place in recovery position (on their side) to protect airway. If not breathing, start CPR if trained.'
    },
    {
      category: 'ELECTROCUTION_OR_LIVE_WIRE',
      regex: /(high[- ]tension\s*wire|live\s*(electric|power)\s*wire|snapped\s*wire|electrocution|bijli\s*ka\s*taar|downed\s*cable)/i,
      minUrgency: 'Immediate',
      advice: 'ELECTRICAL HAZARD DETECTED: DO NOT ENTER WATER OR TOUCH CONDUCTIVE OBJECTS. Keep bystanders at least 30 meters away. Alert power discom to trip feeder line immediately.'
    },
    {
      category: 'TRAPPED_PERSONS_OR_FLOOD',
      regex: /(trapped\s*(people|kids|children|passengers)|submerged\s*bus|drowning|building\s*collapse|malbe\s*me\s*dabe)/i,
      minUrgency: 'Immediate',
      advice: 'MASS CIVILIAN ENTRAPMENT / FLOOD HAZARD: Dispatch Fire Services & Disaster Response (112 / 101). Do not attempt solo water crossings without safety lines.'
    },
    {
      category: 'SEVERE_BLEEDING',
      regex: /(severe\s*bleeding|heavy\s*bleeding|massive\s*hemorrhage|khoon\s*beh\s*raha|arterial\s*spurt)/i,
      minUrgency: 'Immediate',
      advice: 'SEVERE HEMORRHAGE DETECTED: Apply firm, direct continuous pressure using a clean cloth. Elevate limb if possible and call 112 for emergent surgical trauma triage.'
    }
  ];

  let matchedEmergency = false;
  let topAdvice = null;

  for (const marker of emergencyMarkers) {
    if (marker.regex.test(combinedText)) {
      matchedEmergency = true;
      analysis.urgency = marker.minUrgency;
      if (!topAdvice) topAdvice = marker.advice;
    }
  }

  if (matchedEmergency && topAdvice) {
    // Ensure human guidance has the deterministic emergency instruction as step 1
    if (!analysis.humanGuidance.some(g => g.includes('112'))) {
      analysis.humanGuidance.unshift(topAdvice);
    }

    // Boost top action priority to Critical
    if (analysis.actions.length > 0) {
      analysis.actions[0].priority = 'Critical';
      analysis.actions[0].timing = 'Immediate (< 2 mins)';
    }

    // Safety note guarantee
    const overrideNote = `DETERMINISTIC EMERGENCY SAFEGUARD ACTIVE: High-risk danger signals were detected in this report. Dial 112 / 108 immediately. Do not delay real-world medical or disaster response for AI output. SAARTHI AI does not perform clinical diagnosis, triage dispatch, or prescription authorization.`;
    analysis.safety_note = overrideNote;
    analysis.safetyNotes = [overrideNote, ...(analysis.safetyNotes || [])];
  }

  return analysis;
}

