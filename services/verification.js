/**
 * SAARTHI AI — Evidence Verification Adapter
 * 
 * Manages external evidence extraction and claim validation.
 * Extracts authentic grounding metadata from Gemini (Google Search Grounding)
 * and maps claims against real external public domain sources.
 * 
 * Crucial Rule: Never fabricate citations, URLs, or excerpts.
 * If evidence cannot be independently verified, status is set to "Verification unavailable" or "Unverified".
 */

class VerificationAdapter {
  constructor(options = {}) {
    this.options = options;
  }

  /**
   * Process and normalize Gemini grounding metadata into structured evidence objects
   * @param {Object} groundingMetadata - The candidate.groundingMetadata object from Gemini
   * @returns {Array} List of authentic evidence items
   */
  extractGroundingEvidence(groundingMetadata) {
    if (!groundingMetadata || typeof groundingMetadata !== 'object') {
      return [];
    }

    const evidenceList = [];
    const chunks = Array.isArray(groundingMetadata.groundingChunks) ? groundingMetadata.groundingChunks : [];
    const queries = Array.isArray(groundingMetadata.webSearchQueries) ? groundingMetadata.webSearchQueries : [];

    for (let i = 0; i < chunks.length; i++) {
      const chunk = chunks[i];
      if (chunk && chunk.web) {
        const uri = chunk.web.uri || '';
        const title = chunk.web.title || 'Verified Public Web Source';
        
        // Find matching supports if any
        let snippet = '';
        if (Array.isArray(groundingMetadata.groundingSupports)) {
          const support = groundingMetadata.groundingSupports.find(s => 
            Array.isArray(s.groundingChunkIndices) && s.groundingChunkIndices.includes(i)
          );
          if (support && support.segment && support.segment.text) {
            snippet = support.segment.text;
          }
        }

        if (uri) {
          evidenceList.push({
            id: `ev-${i + 1}`,
            source: title,
            url: uri,
            snippet: snippet || `Retrieved via grounding query: "${queries.join(' | ') || title}"`,
            retrievedAt: new Date().toISOString()
          });
        }
      }
    }

    return evidenceList;
  }

  /**
   * Map claims against real retrieved grounding evidence.
   * If a claim has no verifiable evidence, downgrade its status.
   * @param {Array} rawClaims - The claims array generated by the model
   * @param {Array} authenticEvidence - Authenticated evidence items from grounding
   * @returns {Array} Verified claims with honest status badges
   */
  correlateClaimsWithEvidence(rawClaims, authenticEvidence = []) {
    if (!Array.isArray(rawClaims)) return [];

    return rawClaims.map((claimObj, idx) => {
      const claimText = typeof claimObj.claim === 'string' ? claimObj.claim.trim() : '';
      if (!claimText) return null;

      let declaredStatus = claimObj.status || 'Unverified';
      let explanation = claimObj.explanation || '';

      // If authentic evidence exists, check if any evidence URL or title relates
      const matchedEvidence = authenticEvidence.filter(ev => {
        const evText = `${ev.source} ${ev.snippet} ${ev.url}`.toLowerCase();
        const keywords = claimText.toLowerCase().split(/\s+/).filter(w => w.length > 4);
        return keywords.some(k => evText.includes(k));
      });

      // Strict Rule: If no actual grounding evidence matches, do NOT allow 'Verified'
      if (matchedEvidence.length === 0) {
        if (declaredStatus === 'Verified') {
          declaredStatus = 'Verification unavailable';
          explanation = explanation 
            ? `${explanation} (Note: Direct external web grounding citations were unavailable for this specific statement).`
            : 'Independent external retrieval returned no verifiable source citations.';
        }
      }

      return {
        claim: claimText,
        status: declaredStatus,
        evidence: matchedEvidence.length > 0 ? matchedEvidence : (claimObj.evidence || []),
        explanation
      };
    }).filter(Boolean);
  }

  /**
   * Return verified summary of ground truth indicators
   */
  getEvidenceSummary(verifiedClaims = []) {
    const total = verifiedClaims.length;
    const verified = verifiedClaims.filter(c => c.status === 'Verified').length;
    const partial = verifiedClaims.filter(c => c.status === 'Partially verified').length;
    const unverified = verifiedClaims.filter(c => c.status === 'Unverified' || c.status === 'Verification unavailable').length;
    const contradicted = verifiedClaims.filter(c => c.status === 'Contradicted').length;

    return {
      total,
      verified,
      partial,
      unverified,
      contradicted,
      hasExternalProof: verified > 0
    };
  }
}

module.exports = {
  VerificationAdapter
};
